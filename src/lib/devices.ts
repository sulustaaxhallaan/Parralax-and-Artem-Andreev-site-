/**
 * Геометрия экранов в макетах устройств.
 *
 * Экран в этих PNG — прозрачная дырка, а не заливка, поэтому координаты
 * снимались с альфа-канала скриптом (см. историю правок), а не на глаз.
 * Углы даны в процентах от размера картинки, по часовой стрелке с
 * левого верхнего. У ноутбука экран в перспективе — это четырёхугольник,
 * а не прямоугольник, поэтому четыре угла, а не bbox.
 */

export type ScreenGeometry = {
  /** Углы экрана в % от картинки: [x, y] */
  corners: [number, number][];
  /** Центр экрана в % — вокруг него идёт наезд камеры */
  center: [number, number];
  /** Доля картинки, которую занимает экран — из неё считается масштаб наезда */
  span: { width: number; height: number };
  /** Запас, с которым экран должен накрыть кадр. Скошенному экрану нужен
   *  большой — его углы обязаны уйти далеко за край; почти прямоугольному
   *  хватает малого, а лишний запас раздувает картинку и заставляет
   *  браузер перерисовывать огромный слой. */
  coverMargin: number;
};

