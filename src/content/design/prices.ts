/** Как читать цену: «от» зависит от объёма, остальные два очевидны. */
export type PriceKind = "От" | "Фиксированная" | "Индивидуально";

export type PriceService = {
    title: string;
    price: string;
    kind: PriceKind;
    description: string;
    /**
     * Обычный срок, без наценки за срочность. Необязательно: у AI-видео
     * срок зависит от задачи, и выдумывать его в прайсе незачем.
     */
    deadline?: string;
    /**
     * Сколько раундов правок входит в цену. Необязательно: у брендинга
     * объём правок прайсом не задаётся, он обсуждается по проекту —
     * почему именно так, сказано в note категории.
     */
    revisions?: string;
    /** состав работы и оговорки — на странице раскрываются по клику */
    details?: string[];
};

export type PriceCategory = {
    name: string;
    /** якорь для навигации по категориям */
    slug: string;
    /** пояснение ко всей категории — стоит под её заголовком */
    note?: string;
    services: PriceService[];
    /** после услуг — условия и калькулятор AI-ролика (см. aiVideo ниже) */
    withAiVideoCalculator?: boolean;
};

